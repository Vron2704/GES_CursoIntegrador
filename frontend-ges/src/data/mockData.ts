// Convert Historical records to MovimientoModel
export const mapHistoricalRecordToMovimiento = (rec: KardexRecord): MovimientoModel => {
  const isSalida = (rec.cant_salida > 0 || !!rec.guia_salida);

  return {
    idMovimiento: rec.id_movimiento,
    tipoMovimiento: isSalida ? 'SALIDA' : 'INGRESO',
    fechaHora: rec.fecha_ingreso ? `${rec.fecha_ingreso}T${rec.hora_ingreso || '12:00:00'}` : new Date().toISOString(),
    hora: rec.hora_ingreso || '12:00:00',
    uull: rec.uull || 'JABA NEGRA',
    stock: rec.stock,
    guiaIngreso: rec.guia_ingreso || undefined,
    cantIngreso: rec.cant_ingreso || 0,
    cantRechazo: rec.cant_rechazo || 0,
    decomisoNoConforme: rec.decomiso_no_conforme || 0,
    decomisoSobreStock: rec.decomiso_sobre_stock || 0,
    alquiler: rec.alquiler || 0,
    devolucion: rec.devolucion || 0,
    guiaSalida: rec.guia_salida || undefined,
    cantSalida: rec.cant_salida || 0,
    observaciones: rec.observacion || (isSalida ? `Despacho de ${rec.cant_salida} ${rec.uull}` : `Ingreso de ${rec.cant_ingreso} ${rec.uull}`),
    placaVehiculo: rec.placa || (rec.id_movimiento % 2 === 0 ? 'ALT-798' : 'BXR-715'),
    dniConductor: rec.licencia_dni || '10115063',
    nombreConductor: 'CONDUCTOR LOGÍSTICO SPSA',
    licenciaConductor: rec.licencia_dni || '10115063',
    rucProveedor: rec.ruc,
    razonSocialProveedor: rec.razon_social,
    unidadLogistica: '918-Spsa Cd Acopio',
    turno: rec.turno_ingreso || rec.turno_salida || '1-MAÑANA',
    usuarioRegistro: 'op_logistica',
    numeroGuiaAsociada: rec.guia_salida || rec.guia_ingreso || undefined,
    estado: isSalida ? 'COMPLETADO' : (rec.estado_unidad === 'PENDIENTE_SALIDA' ? 'PENDIENTE_SALIDA' : 'EN_ESPERA'),
    pesoBruto: rec.cant_ingreso,
    pesoTara: 0,
    pesoNeto: rec.cant_salida || rec.cant_ingreso,
  };
};

export const INITIAL_MOVIMIENTOS: MovimientoModel[] = HISTORICAL_KARDEX_DATA.map(mapHistoricalRecordToMovimiento);

